use crate::ast::*;
use crate::ontology::OntologyRegistry;
use std::cell::RefCell;
use std::collections::BTreeMap;

thread_local! {
    /// User fns with a spec twin (`spec_<name>`), mapped to which params are `Int` (the twin
    /// takes `int`, so spec-context call sites cast those arguments).
    static SPEC_TWINS: RefCell<BTreeMap<String, Vec<bool>>> = const { RefCell::new(BTreeMap::new()) };
    /// The enclosing fn's `requires`, restated on its loops: Verus does not carry preconditions into `while` invariants.
    static FN_REQUIRES: RefCell<Option<String>> = const { RefCell::new(None) };
    /// Names of user-declared `fn`s, which shadow the built-in `max`/`min`/`abs` helpers.
    static USER_FNS: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
    /// Variant name -> owning enum, so `Soak` is emitted as `Phase::Soak` (Rust has no bare variants).
    static VARIANT_OWNER: RefCell<BTreeMap<String, String>> = const { RefCell::new(BTreeMap::new()) };
}

fn qualify_variant(name: &str) -> String {
    VARIANT_OWNER.with(|m| match m.borrow().get(name) {
        Some(owner) => format!("{owner}::{name}"),
        None => name.to_string(),
    })
}

/// Emits Verus (`verus! { ... }`) Rust verification code from a checked `.bil` program.
/// Bridges OntoLogic concepts/axioms, Dijkstra GCL (`if..fi`, `do..od`), `spec`/`refines`,
/// and `system` state machines directly to Verus's `spec fn`, `proof`, and `exec fn` model.
pub fn emit_verus_rust(program: &Program, ontology: &OntologyRegistry) -> String {
    USER_FNS.with(|u| {
        *u.borrow_mut() = program
            .items
            .iter()
            .filter_map(|i| match i {
                Item::FnDecl(f) => Some(f.name.clone()),
                _ => None,
            })
            .collect();
    });
    SPEC_TWINS.with(|t| {
        let mut t = t.borrow_mut();
        t.clear();
        for item in &program.items {
            if let Item::FnDecl(f) = item {
                if has_spec_twin(f) {
                    t.insert(
                        f.name.clone(),
                        f.params.iter().map(|p| is_int_ty(&p.ty)).collect(),
                    );
                }
            }
        }
    });
    VARIANT_OWNER.with(|m| {
        let mut m = m.borrow_mut();
        m.clear();
        for item in &program.items {
            if let Item::TypeDecl(adt) = item {
                for v in &adt.variants {
                    m.insert(v.name.clone(), adt.name.clone());
                }
            }
        }
    });
    let mut out = String::new();
    out.push_str("// Auto-generated by `bil emit-verus` — Verus Provably Correct Rust Backend\n");
    out.push_str("use vstd::prelude::*;\n\n");
    out.push_str("verus! {\n\n");

    // 1. Emit OntoLogic Concepts as Rust structs with inherited fields
    for (cname, cinfo) in &ontology.concepts {
        let structural = if cinfo.all_fields.iter().any(|(_, t)| mentions_string(t)) { "" } else { "Structural, " };
        out.push_str(&format!("#[derive(PartialEq, Eq, {structural}Clone)]\n"));
        out.push_str(&format!("pub struct {} {{\n", cname));
        for (fname, fty) in &cinfo.all_fields {
            out.push_str(&format!("    pub {}: {},\n", fname, verus_type(fty)));
        }
        out.push_str("}\n\n");
    }

    // 2. Emit Algebraic Data Types (ADTs)
    for item in &program.items {
        if let Item::TypeDecl(adt) = item {
            // `String` is neither `Structural` nor `Copy` in vstd/std.
            let has_string = adt.variants.iter().any(|v| v.payload.iter().any(mentions_string));
            let derives = if has_string { "PartialEq, Eq, Clone" } else { "PartialEq, Eq, Structural, Clone, Copy" };
            out.push_str(&format!("#[derive({derives})]\n"));
            out.push_str(&format!("pub enum {} {{\n", adt.name));
            for v in &adt.variants {
                if v.payload.is_empty() {
                    out.push_str(&format!("    {},\n", v.name));
                } else {
                    let p: Vec<String> = v.payload.iter().map(verus_type).collect();
                    out.push_str(&format!("    {}({}),\n", v.name, p.join(", ")));
                }
            }
            out.push_str("}\n\n");
        }
    }

    // Built-in numeric helpers the `.bil` expression language provides; skipped when user-defined.
    // Spec contexts call `spec_*` (unbounded int); exec bodies call the i64 exec fns.
    let user_fns: Vec<&str> = program
        .items
        .iter()
        .filter_map(|i| match i {
            Item::FnDecl(f) => Some(f.name.as_str()),
            _ => None,
        })
        .collect();
    let builtins = [
        (
            "max",
            "pub open spec fn spec_max(a: int, b: int) -> int {\n    if a >= b { a } else { b }\n}\n\n\
             pub fn max(a: i64, b: i64) -> (r: i64)\n    ensures r == spec_max(a as int, b as int),\n{\n    if a >= b { a } else { b }\n}\n\n",
        ),
        (
            "min",
            "pub open spec fn spec_min(a: int, b: int) -> int {\n    if a <= b { a } else { b }\n}\n\n\
             pub fn min(a: i64, b: i64) -> (r: i64)\n    ensures r == spec_min(a as int, b as int),\n{\n    if a <= b { a } else { b }\n}\n\n",
        ),
        (
            "abs",
            "pub open spec fn spec_abs(a: int) -> int {\n    if a >= 0 { a } else { -a }\n}\n\n\
             pub fn abs(a: i64) -> (r: i64)\n    requires a > i64::MIN,\n    ensures r == spec_abs(a as int),\n{\n    if a >= 0 { a } else { -a }\n}\n\n",
        ),
    ];
    for (name, src) in builtins {
        if !user_fns.contains(&name) {
            out.push_str(src);
        }
    }

    // 3. Emit OntoLogic Axioms as Verus `open spec fn` predicates
    for item in &program.items {
        if let Item::Axiom(ax) = item {
            match &ax.formula {
                Expr::Quantifier {
                    kind: QuantifierKind::Forall,
                    var,
                    domain,
                    body,
                } => {
                    let dom_ty = match &**domain {
                        Expr::Var(c) if ontology.concepts.contains_key(c) => c.clone(),
                        _ => "i64".to_string(),
                    };
                    out.push_str(&format!(
                        "pub open spec fn axiom_{}({}: {}) -> bool {{\n    {}\n}}\n\n",
                        ax.name,
                        var,
                        dom_ty,
                        verus_expr(body, true)
                    ));
                }
                other => {
                    out.push_str(&format!(
                        "pub open spec fn axiom_{}() -> bool {{\n    {}\n}}\n\n",
                        ax.name,
                        verus_expr(other, true)
                    ));
                }
            }
        }
    }

    // 4. Emit Abstract Specifications (`spec`) as Verus `open spec fn` contracts
    for item in &program.items {
        if let Item::Spec(sp) = item {
            let mut params: Vec<String> = sp
                .params
                .iter()
                .map(|p| format!("{}: {}", p.name, verus_type(&p.ty)))
                .collect();
            params.push(format!("result: {}", verus_type(&sp.ret_ty)));

            let req = sp
                .requires
                .as_ref()
                .map(|e| verus_expr(e, true))
                .unwrap_or_else(|| "true".into());
            let ens = sp
                .ensures
                .as_ref()
                .map(|e| verus_expr(e, true))
                .unwrap_or_else(|| "true".into());

            out.push_str(&format!(
                "pub open spec fn {}_contract({}) -> bool {{\n    ({}) ==> ({})\n}}\n\n",
                sp.name,
                params.join(", "),
                req,
                ens
            ));
        }
    }

    // 4b. Emit Verus Ghost Proof Lemmas (`proof`) as `pub proof fn`
    for item in &program.items {
        if let Item::Proof(pr) = item {
            let params: Vec<String> = pr
                .params
                .iter()
                .map(|p| format!("{}: {}", p.name, verus_type(&p.ty)))
                .collect();
            out.push_str(&format!("pub proof fn {}({})\n", pr.name, params.join(", ")));
            if let Some(req) = &pr.requires {
                out.push_str(&format!("    requires\n        {},\n", verus_expr(req, true)));
            }
            out.push_str(&format!(
                "    ensures\n        {},\n",
                verus_expr(&pr.ensures, true)
            ));
            if let Some(body) = &pr.body {
                out.push_str(&format!("{{\n    assert({});\n}}\n\n", verus_expr(body, true)));
            } else {
                out.push_str("{\n}\n\n");
            }
        }
    }

    // 5. Emit Verified Functions (`fn`) with `requires`, `ensures`, `refines`, and GCL bodies
    for item in &program.items {
        if let Item::FnDecl(f) = item {
            let params: Vec<String> = f
                .params
                .iter()
                .map(|p| format!("{}: {}", p.name, verus_type(&p.ty)))
                .collect();
            if has_spec_twin(f) {
                let tparams: Vec<String> = f
                    .params
                    .iter()
                    .map(|p| format!("{}: {}", p.name, spec_ty(&p.ty)))
                    .collect();
                out.push_str(&format!(
                    "pub open spec fn spec_{}({}) -> {} {{\n    {}\n}}\n\n",
                    f.name,
                    tparams.join(", "),
                    spec_ty(&f.ret_ty),
                    verus_expr(&f.body, true)
                ));
            }
            out.push_str(&format!(
                "pub fn {}({}) -> (result: {})\n",
                f.name,
                params.join(", "),
                verus_type(&f.ret_ty)
            ));
            FN_REQUIRES.with(|r| *r.borrow_mut() = f.requires.as_ref().map(|q| verus_expr(q, true)));
            if let Some(req) = &f.requires {
                out.push_str(&format!("    requires\n        {},\n", verus_expr(req, true)));
            }
            let mut ensures_clauses = Vec::new();
            if let Some(ens) = &f.ensures {
                ensures_clauses.push(verus_expr(ens, true));
            }
            if has_spec_twin(f) {
                let args: Vec<String> = f
                    .params
                    .iter()
                    .map(|p| if is_int_ty(&p.ty) { format!("{} as int", p.name) } else { p.name.clone() })
                    .collect();
                ensures_clauses.push(format!("result == spec_{}({})", f.name, args.join(", ")));
            }
            if let Some(spec_name) = &f.refines {
                let mut call_args: Vec<String> = f.params.iter().map(|p| p.name.clone()).collect();
                call_args.push("result".into());
                ensures_clauses.push(format!("{}_contract({})", spec_name, call_args.join(", ")));
            }
            if !ensures_clauses.is_empty() {
                out.push_str("    ensures\n");
                for c in ensures_clauses {
                    out.push_str(&format!("        {},\n", c));
                }
            }
            if let Some(var) = &f.variant {
                out.push_str(&format!(
                    "    decreases\n        {},\n",
                    verus_expr(var, true)
                ));
            }
            out.push_str("{\n");
            out.push_str(&verus_fn_body(&f.body, 1));
            FN_REQUIRES.with(|r| *r.borrow_mut() = None);
            out.push_str("}\n\n");
        }
    }

    // 6. Emit Concurrent / Nondeterministic `system` Blocks as Verus State-Machine Invariant Structs
    for item in &program.items {
        if let Item::System(sys) = item {
            out.push_str(&format!("pub struct {}State {{\n", sys.name));
            for st in &sys.states {
                out.push_str(&format!("    pub {}: {},\n", st.name, verus_type(&st.ty)));
            }
            out.push_str("}\n\n");

            out.push_str(&format!("impl {}State {{\n", sys.name));
            // Emit Lock / State Invariant predicate (`inv`)
            out.push_str("    pub open spec fn invariant(&self) -> bool {\n");
            if sys.invariants.is_empty() {
                out.push_str("        true\n");
            } else {
                let invs: Vec<String> = sys
                    .invariants
                    .iter()
                    .map(|i| format!("({}) /* {} */", verus_self_expr(&i.formula, &sys.states), i.name))
                    .collect();
                out.push_str(&format!("        {}\n", invs.join("\n        && ")));
            }
            out.push_str("    }\n\n");

            // Initializer proving invariant holds initially
            out.push_str("    pub fn init() -> (s: Self)\n        ensures s.invariant(),\n    {\n");
            out.push_str("        Self {\n");
            for st in &sys.states {
                out.push_str(&format!(
                    "            {}: {},\n",
                    st.name,
                    verus_expr(&st.init, false)
                ));
            }
            out.push_str("        }\n    }\n");

            // One step per guarded transition. Updates are simultaneous: every right-hand side
            // is evaluated on the pre-state before any field is assigned.
            for (i, tr) in sys.transitions.iter().enumerate() {
                out.push_str(&format!("\n    pub fn step_{i}(&mut self)\n"));
                out.push_str("        requires\n            old(self).invariant(),\n");
                out.push_str(&format!(
                    "            {},\n",
                    verus_state_expr(&tr.guard, &sys.states, "old(self)", true)
                ));
                out.push_str("        ensures\n            final(self).invariant(),\n");
                for st in &sys.states {
                    match tr.updates.iter().find(|(v, _)| *v == st.name) {
                        Some((_, e)) => out.push_str(&format!(
                            "            final(self).{} == {},\n",
                            st.name,
                            verus_state_expr(e, &sys.states, "old(self)", true)
                        )),
                        None => out.push_str(&format!(
                            "            final(self).{n} == old(self).{n},\n",
                            n = st.name
                        )),
                    }
                }
                out.push_str("    {\n");
                for (j, (_, e)) in tr.updates.iter().enumerate() {
                    out.push_str(&format!(
                        "        let _n{j} = {};\n",
                        verus_state_expr(e, &sys.states, "self", false)
                    ));
                }
                for (j, (v, _)) in tr.updates.iter().enumerate() {
                    out.push_str(&format!("        self.{v} = _n{j};\n"));
                }
                out.push_str("    }\n");
            }
            out.push_str("}\n\n");
        }
    }

    out.push_str("} // verus!\n");
    out
}

/// `v := e` as a Rust statement. `v := v with {..}` updates the fields in place (via temporaries,
/// so every right-hand side sees the old value): Verus gives `clone()` no spec, losing the fields.
fn assign_stmt(pad: &str, v: &str, ue: &Expr) -> String {
    if let Expr::RecordWith { base, updates } = ue {
        if matches!(&**base, Expr::Var(b) if b == v) {
            let mut out = String::new();
            for (i, (_, e)) in updates.iter().enumerate() {
                out.push_str(&format!("{pad}let _u{i} = {};\n", verus_expr(e, false)));
            }
            for (i, (k, _)) in updates.iter().enumerate() {
                out.push_str(&format!("{pad}{v}.{k} = _u{i};\n"));
            }
            return out;
        }
    }
    format!("{pad}{v} = {};\n", verus_expr(ue, false))
}

fn is_int_ty(ty: &TypeExpr) -> bool {
    matches!(ty, TypeExpr::Named(n) if n == "Int" || n == "Integer")
}

/// Spec-context type of a twin's parameter/result: `Int` is unbounded `int`.
fn spec_ty(ty: &TypeExpr) -> String {
    if is_int_ty(ty) { "int".into() } else { verus_type(ty) }
}

/// A user fn gets a `spec_<name>` twin when its body is a plain expression (no loops or matches),
/// so spec contexts (guards, invariants) can call it.
fn has_spec_twin(f: &FnDecl) -> bool {
    match &f.body {
        Expr::DoOd { .. } | Expr::Match { .. } => false,
        Expr::IfFi { branches } => branches.iter().all(|b| matches!(b.body, GclBody::Expr(_))),
        _ => true,
    }
}

fn mentions_string(ty: &TypeExpr) -> bool {
    match ty {
        TypeExpr::Named(n) => matches!(n.as_str(), "String" | "Str"),
        TypeExpr::List(i) => mentions_string(i),
        TypeExpr::Map(k, v) => mentions_string(k) || mentions_string(v),
        TypeExpr::Fn(a, r) => a.iter().any(mentions_string) || mentions_string(r),
    }
}

fn verus_type(ty: &TypeExpr) -> String {
    match ty {
        TypeExpr::Named(n) => match n.as_str() {
            "Int" | "Integer" => "i64".into(),
            "Float" | "Double" => "f64".into(),
            "Bool" | "Boolean" => "bool".into(),
            "String" | "Str" => "String".into(),
            "Unit" => "()".into(),
            other => other.to_string(),
        },
        TypeExpr::List(inner) => format!("Vec<{}>", verus_type(inner)),
        TypeExpr::Map(k, v) => format!("std::collections::BTreeMap<{}, {}>", verus_type(k), verus_type(v)),
        TypeExpr::Fn(args, ret) => {
            let a: Vec<String> = args.iter().map(verus_type).collect();
            format!("fn({}) -> {}", a.join(", "), verus_type(ret))
        }
    }
}

fn verus_fn_body(expr: &Expr, indent: usize) -> String {
    let pad = "    ".repeat(indent);
    match expr {
        Expr::IfFi { branches } => {
            let mut out = String::new();
            // Emit Dijkstra guard totality proof assertion
            let guards: Vec<String> = branches
                .iter()
                .map(|b| format!("({})", verus_expr(&b.guard, true)))
                .collect();
            out.push_str(&format!(
                "{}proof {{ assert({}); }} // GCL Guard Totality (BB)\n",
                pad,
                guards.join(" || ")
            ));
            for (idx, br) in branches.iter().enumerate() {
                let kw = if idx == 0 {
                    format!("if {}", verus_expr(&br.guard, false))
                } else if idx + 1 == branches.len() {
                    "else".to_string()
                } else {
                    format!("else if {}", verus_expr(&br.guard, false))
                };
                out.push_str(&format!("{}{} {{\n", pad, kw));
                match &br.body {
                    GclBody::Expr(e) => {
                        out.push_str(&format!("{}    {}\n", pad, verus_expr(e, false)));
                    }
                    GclBody::Updates(ups) => {
                        for (v, ue) in ups {
                            out.push_str(&assign_stmt(&format!("{}    ", pad), v, ue));
                        }
                    }
                    GclBody::Skip => out.push_str(&format!("{}    ()\n", pad)),
                    GclBody::Abort => out.push_str(&format!("{}    proof {{ assert(false); }}\n", pad)),
                }
                out.push_str(&format!("{}}}\n", pad));
            }
            out
        }
        Expr::DoOd {
            inits,
            invariant,
            variant,
            branches,
            then_expr,
        } => {
            let mut out = String::new();
            for (vname, iexpr) in inits {
                // `.bil` integer literals are `Int`; a suffix keeps invariants like `ticks + rem` inferable.
                let init = match iexpr {
                    Expr::Int(v) => format!("{v}i64"),
                    other => verus_expr(other, false),
                };
                out.push_str(&format!("{}let mut {} = {};\n", pad, vname, init));
            }
            let bb: Vec<String> = branches
                .iter()
                .map(|b| format!("({})", verus_expr(&b.guard, false)))
                .collect();
            out.push_str(&format!("{}while {}\n", pad, bb.join(" || ")));
            let mut invs: Vec<String> = invariant.iter().map(|i| verus_expr(i, true)).collect();
            invs.extend(FN_REQUIRES.with(|r| r.borrow().clone()));
            if !invs.is_empty() {
                out.push_str(&format!("{}    invariant\n", pad));
                for i in invs {
                    out.push_str(&format!("{}        {},\n", pad, i));
                }
            }
            if let Some(var_e) = variant {
                out.push_str(&format!(
                    "{}    decreases\n{}        {},\n",
                    pad,
                    pad,
                    verus_expr(var_e, true)
                ));
            }
            out.push_str(&format!("{}{{\n", pad));
            for (idx, br) in branches.iter().enumerate() {
                let kw = if idx == 0 { "if" } else { "else if" };
                out.push_str(&format!(
                    "{}    {} {} {{\n",
                    pad,
                    kw,
                    verus_expr(&br.guard, false)
                ));
                match &br.body {
                    GclBody::Updates(ups) => {
                        for (v, ue) in ups {
                            out.push_str(&assign_stmt(&format!("{}        ", pad), v, ue));
                        }
                    }
                    GclBody::Expr(e) => {
                        let first_var = &inits[0].0;
                        out.push_str(&format!(
                            "{}        {} = {};\n",
                            pad,
                            first_var,
                            verus_expr(e, false)
                        ));
                    }
                    GclBody::Skip => {}
                    GclBody::Abort => {
                        out.push_str(&format!("{}        proof {{ assert(false); }}\n", pad));
                    }
                }
                out.push_str(&format!("{}    }}\n", pad));
            }
            out.push_str(&format!("{}}}\n", pad));
            out.push_str(&format!("{}{}\n", pad, verus_expr(then_expr, false)));
            out
        }
        other => format!("{}{}\n", pad, verus_expr(other, false)),
    }
}

#[allow(clippy::only_used_in_recursion)]
fn verus_expr(expr: &Expr, in_spec: bool) -> String {
    match expr {
        Expr::Int(v) => v.to_string(),
        Expr::Float(v) => crate::expr_utils::format_float(*v),
        Expr::Bool(v) => v.to_string(),
        Expr::Str(s) => format!("{:?}.to_string()", s),
        Expr::Var(v) => qualify_variant(v),
        Expr::Placeholder => "_".into(),
        Expr::Unary { op, expr: inner } => match op {
            UnaryOp::Not => format!("!({})", verus_expr(inner, in_spec)),
            UnaryOp::Neg => format!("-({})", verus_expr(inner, in_spec)),
        },
        // Spec code cannot build a `String`; compare views (`Seq<char>`) against the literal instead.
        Expr::Binary { op: op @ (BinOp::Eq | BinOp::Neq), left, right }
            if in_spec && (matches!(**left, Expr::Str(_)) || matches!(**right, Expr::Str(_))) =>
        {
            let view = |e: &Expr| match e {
                Expr::Str(s) => format!("{:?}@", s),
                other => format!("{}@", verus_expr(other, in_spec)),
            };
            let op_str = if matches!(op, BinOp::Eq) { "==" } else { "!=" };
            format!("({} {} {})", view(left), op_str, view(right))
        }
        Expr::Binary { op, left, right } => {
            let l = verus_expr(left, in_spec);
            let r = verus_expr(right, in_spec);
            let op_str = match op {
                BinOp::Implies => "==>",
                BinOp::Iff => "<==>",
                BinOp::And => "&&",
                BinOp::Or => "||",
                BinOp::Eq => "==",
                BinOp::Neq => "!=",
                BinOp::Lt => "<",
                BinOp::Le => "<=",
                BinOp::Gt => ">",
                BinOp::Ge => ">=",
                BinOp::Add => "+",
                BinOp::Sub => "-",
                BinOp::Mul => "*",
                BinOp::Div => "/",
                BinOp::Mod => "%",
                _ => "==",
            };
            format!("({} {} {})", l, op_str, r)
        }
        Expr::Quantifier {
            kind,
            var,
            domain,
            body,
        } => {
            if let Expr::Binary {
                op: BinOp::RangeInc,
                left,
                right,
            } = &**domain
            {
                let q = match kind {
                    QuantifierKind::Forall => "forall",
                    QuantifierKind::Exists => "exists",
                    QuantifierKind::Choose => "choose",
                };
                format!(
                    "{}|_v: int| ({} <= {} && {} <= {}) ==> {}",
                    q,
                    verus_expr(left, true),
                    var,
                    var,
                    verus_expr(right, true),
                    verus_expr(body, true)
                )
            } else {
                let q = match kind {
                    QuantifierKind::Forall => "forall",
                    QuantifierKind::Exists => "exists",
                    QuantifierKind::Choose => "choose",
                };
                format!("{}|{}: i64| {}", q, var, verus_expr(body, true))
            }
        }
        Expr::FieldAccess { base, field } => format!("{}.{}", verus_expr(base, in_spec), field),
        Expr::RecordInit { concept, fields } => {
            let fs: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("{}: {}", k, verus_expr(v, in_spec)))
                .collect();
            format!("{} {{ {} }}", concept, fs.join(", "))
        }
        Expr::RecordWith { base, updates } => {
            let b = verus_expr(base, in_spec);
            let us: Vec<String> = updates
                .iter()
                .map(|(k, v)| format!("_tmp.{} = {};", k, verus_expr(v, in_spec)))
                .collect();
            format!("{{ let mut _tmp = {}.clone(); {} _tmp }}", b, us.join(" "))
        }
        Expr::Call { func, args } => {
            let a: Vec<String> = args.iter().map(|x| verus_expr(x, in_spec)).collect();
            let twin = in_spec.then(|| SPEC_TWINS.with(|t| t.borrow().get(func).cloned())).flatten();
            if let Some(int_params) = twin {
                let a: Vec<String> = args
                    .iter()
                    .zip(int_params.iter().chain(std::iter::repeat(&false)))
                    .map(|(x, is_int)| {
                        let e = verus_expr(x, true);
                        if *is_int { format!("({e}) as int") } else { e }
                    })
                    .collect();
                return format!("spec_{func}({})", a.join(", "));
            }
            let builtin = matches!(func.as_str(), "max" | "min" | "abs")
                && !USER_FNS.with(|u| u.borrow().contains(func));
            if builtin && in_spec {
                format!("spec_{}({})", func, a.join(", "))
            } else {
                format!("{}({})", qualify_variant(func), a.join(", "))
            }
        }
        // Value-position `if..fi` (e.g. timed-lowering counters); like fn bodies, the last branch is the `else`.
        Expr::IfFi { branches } if branches.iter().all(|b| matches!(b.body, GclBody::Expr(_))) => {
            let mut out = String::new();
            for (i, b) in branches.iter().enumerate() {
                let GclBody::Expr(e) = &b.body else { unreachable!() };
                let val = verus_expr(e, in_spec);
                if i + 1 == branches.len() {
                    out.push_str(&if i == 0 { val } else { format!("else {{ {val} }}") });
                } else {
                    let kw = if i == 0 { "if" } else { "else if" };
                    out.push_str(&format!("{kw} {} {{ {val} }} ", verus_expr(&b.guard, in_spec)));
                }
            }
            format!("({out})")
        }
        _ => "()".into(),
    }
}

fn verus_self_expr(expr: &Expr, states: &[StateVarDecl]) -> String {
    verus_state_expr(expr, states, "self", true)
}

/// `expr` with every state variable read as a field of `base` (`self`, `old(self)`).
fn verus_state_expr(expr: &Expr, states: &[StateVarDecl], base: &str, in_spec: bool) -> String {
    let mut map = std::collections::BTreeMap::new();
    for st in states {
        map.insert(st.name.clone(), Expr::Var(format!("{base}.{}", st.name)));
    }
    let substituted = crate::expr_utils::subst_expr(expr, &map);
    verus_expr(&substituted, in_spec)
}
